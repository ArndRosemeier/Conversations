// Rebuild the committed browser module with the actual GF compiler.
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync, mkdirSync, copyFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, dirname, delimiter} from 'node:path';
const here=dirname(fileURLToPath(import.meta.url));
const compiler=process.env.GF_BIN || resolve(here,'.tooling/gf-3.12/gf.exe');
const rgl=process.env.GF_RGL_PATH || resolve(here,'.tooling/gf-rgl-20260403/gf-rgl-20260403');
const searchPath=['.',resolve(rgl,'alltenses'),resolve(rgl,'prelude')].join(delimiter);
execFileSync(compiler,['-make',`-path=${searchPath}`,'--output-format=js','ConversationEng.gf'],{cwd:here,stdio:'inherit'});
// Upstream's legacy script deletes a local binding (a no-op forbidden in ESM).
// Preserve the vendored original and make this compatibility patch explicitly.
const runtime=readFileSync(resolve(here,'vendor/gflib.js'),'utf8')
  .replace('delete(ps2);','/* ESM compatibility: removed no-op delete(ps2). */')
  .replace('var me = arguments.callee;','var me = tagIt;')
  .replace('function (obj, tag) {','function tagIt(obj, tag) {');
const grammar=readFileSync(resolve(here,'Conversation.js'),'utf8');
const out=resolve(here,'../dist/languages/en/gf');
mkdirSync(out,{recursive:true});
writeFileSync(resolve(out,'grammar.mjs'),`// Generated by GF 3.12. Runtime: GF dual LGPL/BSD; see GF-LICENSE.txt.\n${runtime}\n${grammar}\nexport {Conversation, Fun};\n`);
copyFileSync(resolve(here,'adapter.mjs'),resolve(out,'adapter.mjs'));
copyFileSync(resolve(here,'vendor/GF-LICENSE.txt'),resolve(out,'GF-LICENSE.txt'));
copyFileSync(resolve(here,'vendor/RGL-LICENSE.txt'),resolve(out,'RGL-LICENSE.txt'));
copyFileSync(resolve(here,'LICENSE.txt'),resolve(out,'APP-LICENSE.txt'));
copyFileSync(resolve(here,'sources.json'),resolve(out,'sources.json'));
